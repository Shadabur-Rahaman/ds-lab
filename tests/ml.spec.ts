import {readFileSync} from 'node:fs';
import {expect, test} from './fixtures';
import {binaryMetrics, classify, fitIris, fitLine, fitPolynomial, curveData, parseIris, regressionMetrics, splitRows} from '../src/lib/ml';

test('ML math matches known fits, predictions, splits and metric edge cases', () => {
  const line = fitLine([{x: 1, y: 3}, {x: 2,y: 5}, {x: 3,y: 7}])!;
  expect([line.slope,line.intercept,line.predict(6)]).toEqual([2,1,13]);
  expect(fitLine([{x: 1,y: 2}, {x: 1,y: 3}])).toBeNull();
  expect(regressionMetrics([{x: 1,y: 2}, {x: 2,y: 6}], x=>2*x)).toEqual({mae:1,mse:2,r2:.5});
  expect(regressionMetrics([{x: 1,y: 5}, {x: 2,y: 5}], ()=>5).r2).toBeNull();
  const points = [{features:[0,3],label:'A'}, {features:[2,0],label:'B'}, {features:[3,0],label:'B'}];
  expect(classify(points,[0,0],1).neighbors.map(point=>point.index)).toEqual([1]);
  expect(classify(points,[0,0],1,[3,1]).label).toBe('A');
  expect(classify(points,[0,0],3).label).toBe('B');
  const rows = Array.from({length:20}, (_,x)=>({x,y:x+x%3*2}));
  const split = splitRows(rows,.3,17);
  expect(split).toEqual(splitRows(rows,.3,17));
  expect(split).not.toEqual(splitRows(rows,.3,18));
  expect(split.test.filter(row=>split.train.includes(row))).toHaveLength(0);
  const contaminated = [...split.train,...split.test];
  expect(split.test.filter(row=>contaminated.includes(row))).toHaveLength(6);
  expect(regressionMetrics(split.test,fitLine(split.train)!.predict).mae)
    .not.toEqual(regressionMetrics(split.test,fitLine(contaminated)!.predict).mae);
  expect(binaryMetrics({tp:0,fp:0,tn:0,fn:0})).toEqual({accuracy:null,precision:null,recall:null,specificity:null,f1:null});
  expect(binaryMetrics({tp:0,fp:0,tn:99,fn:1})).toEqual({accuracy:.99,precision:null,recall:0,specificity:1,f1:0});
  const {train,test: held} = curveData(1.4);
  const complex = fitPolynomial(train,12)!;
  const simple = fitPolynomial(train,2)!;
  expect(regressionMetrics(train,complex).mse!).toBeLessThan(1e-10);
  expect(regressionMetrics(held,complex).mse!).toBeGreaterThan(regressionMetrics(held,simple).mse!);
  expect(fitPolynomial([{x:1,y:1},{x:1,y:2}],1)).toBeNull();
});

test('Iris data integrity and confusion matrix agree with actual predictions', () => {
  const csv = readFileSync('public/datasets/iris.csv','utf8');
  const samples = parseIris(csv);
  expect(samples).toHaveLength(150);
  expect(() => parseIris(csv.replace('5.1,','bad,'))).toThrow('Invalid Iris observation.');
  expect(() => parseIris(csv.trim().split(/\r?\n/).slice(0,-1).join('\n'))).toThrow('Expected 50 observations');
  const report = fitIris(samples,[2,3],17,.3,5);
  expect(report.train).toHaveLength(105);
  expect(report.test).toHaveLength(45);
  expect(report.matrix.map(row=>row.reduce((sum,value)=>sum+value,0))).toEqual([15,15,15]);
  expect(report.matrix.reduce((sum,row,index)=>sum+row[index],0)/45).toBeCloseTo(report.testAccuracy);
  expect(report.testAccuracy).toBeGreaterThan(.8);
  expect(fitIris(samples,[2,3],17,.3,5,true).matrix).toHaveLength(2);
});

